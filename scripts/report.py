"""Turn the run's records into results/report.md (the tables FINDINGS.md cites).

Reads, when present:
- results/final.json      (locked test, ablations, submission check: scripts/final.py)
- results/archive.jsonl   (every member and generation: scripts/rsi_loop.py)
- results/notebook.jsonl  (every hypothesis and its test)
- results/long_run.json   (the 2–3 year view: scripts/long_run.py)
- results/engine.md       (the list-replay engine against Pacific's baselines: scripts/engine_check.py)
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def jsonl(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()] if path.is_file() else []


def f(x, spec="+.4f"):
    return "n/a" if x is None else format(x, spec)


def main() -> None:
    lines = ["# Results", "", "Generated by `scripts/report.py` from the files in `results/`.", ""]

    final = json.loads((RES / "final.json").read_text()) if (RES / "final.json").is_file() else {}
    test = final.get("test") or {}
    if test:
        lines += ["## Locked test: 24, 27 and 30 Oct 2026 (frozen-cutoff mode, rental scope, h = 1, 3, 7)", "",
                  "Pooled skill against the last value, with a 90% bootstrap interval over (series, origin) blocks; "
                  "`vs drift` is a paired bootstrap on the same cells. Coverage is the share of truths inside "
                  "[q10, q90] (target 0.80). The Sunday column restricts to the 37 headline series scored on Sunday.", "",
                  "| Variant | Pooled skill | 90% interval | vs drift: delta, P(better) | Coverage | h=1 | h=3 | h=7 | Sunday series | Cells |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        order = sorted(test, key=lambda k: -test[k]["pooled"])
        for k in order:
            t = test[k]
            vs = t.get("vs_drift") or {}
            bh = t.get("by_horizon") or {}
            lines.append(f"| {k} | {f(t['pooled'])} | [{f(t['pooled_90ci'][0])}, {f(t['pooled_90ci'][1])}] | "
                         + (f"{f(vs.get('delta'))}, {vs.get('p_better', 0):.2f}" if vs else "reference")
                         + f" | {t['coverage_80']:.2f} | {f(bh.get('1'))} | {f(bh.get('3'))} | {f(bh.get('7'))} | "
                         f"{f(t.get('sunday_series_pooled'))} | {t['cells']} |")
        lines.append("")
    sub = final.get("submission")
    if sub:
        lines += [f"**Submission:** `{sub['file']}`, {sub['rows']} rows for {sub['series']} series, origin 2026-11-06, "
                  f"horizons 1, 3, 7; Pacific's frozen-cutoff check: `{sub['frozen_check']}`.", ""]

    archive = jsonl(RES / "archive.jsonl")
    members = [r for r in archive if r.get("kind") == "member"]
    gens = [r for r in archive if r.get("kind") == "generation"]
    base = next((r for r in archive if r.get("kind") == "baseline"), None)
    if members:
        lines += ["## Across iterations (validation origins 1, 8 and 15 Oct; truth to 24 Oct)", "",
                  f"Reference: Pacific's `last_value_empirical` on the same cells, pooled {f(base and base.get('val'))}.", "",
                  "| Generation | Member | How it was made | Train reward | Validation pooled | Coverage |",
                  "|---|---|---|---|---|---|"]
        for r in members:
            cov = (r.get("summary") or {}).get("coverage") or {}
            lines.append(f"| {r['gen']} | {r['mid']} | {str(r.get('note', ''))[:110]} | {r['train_reward']:+.3f} | "
                         f"{r['val']:+.4f} | {cov.get('within_q10_q90', 'n/a')} |")
        lines += ["", "| Generation | Best | Accepted as new incumbent | Bootstrap delta vs incumbent | P(better) |",
                  "|---|---|---|---|---|"]
        for g in gens:
            b = g.get("bootstrap") or {}
            lines.append(f"| {g['gen']} | {g['best']} | {'yes' if g['accepted'] else 'no'} | {f(b.get('delta'))} | "
                         f"{b.get('p_better', 0):.2f} |")
        lines.append("")

    notes = jsonl(RES / "notebook.jsonl")
    if notes:
        lines += ["## Research notebook (tested on data up to 30 Sep 2026 only)", "",
                  "| ID | Iteration | Family and parameters | Hypothesis | Result | p | n | Verdict |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in notes:
            h = r["hypothesis"]
            lines.append(f"| {r['hid']} | {r['iteration']} | {h['family']} `{json.dumps(h['params'])}` | {h['statement']} | "
                         f"{r['summary']} | {r['p_value']:.3f} | {r['n']} | {'kept' if r['survived'] else 'rejected'} |")
        lines.append("")

    if (RES / "engine.md").is_file():
        lines += ["## The list-replay engine (no LLM)", "",
                  "See [engine.md](engine.md) (regenerate with `python scripts/engine_check.py`).", ""]
    if (RES / "long_run.md").is_file():
        lines += ["## The 2–3 year view", "", "See [long_run.md](long_run.md) (regenerate with `python scripts/long_run.py`).", ""]
    (RES / "report.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
